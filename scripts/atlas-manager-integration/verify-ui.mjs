import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
import {mkdirSync,writeFileSync} from 'node:fs';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.ATLAS_PLAYWRIGHT_MODULE||'playwright');
const output=new URL('../../.local/atlas-manager-implementation/ui/',import.meta.url);
mkdirSync(output,{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:process.env.ATLAS_CHROME_PATH});
const checks=[],errors=[],external=[];
try{
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 page.on('pageerror',error=>errors.push(error.message));
 await page.route('**/*',route=>{const url=new URL(route.request().url());if(url.hostname==='127.0.0.1'&&url.port==='4341')return route.continue();external.push(url.origin);return route.abort();});
 await page.goto('http://127.0.0.1:4341');
 await page.getByText('Conversas recentes',{exact:true}).click();
 await page.getByRole('button',{name:/Consulta FICTÍCIA/}).click();
 await page.getByText('Pergunta agendada para Conta Exemplo em 19/10 08:00.',{exact:true}).waitFor();
 assert.equal(await page.getByLabel('Seu pedido ao Atlas').isEnabled(),true);
 checks.push('waiting_team visible and composer remains available');
 await page.getByRole('button',{name:/Ver conversa com a equipe/}).focus();await page.keyboard.press('Enter');
 await page.getByText(/Buscando a resposta para a consulta do dono/).waitFor();
 assert.ok(await page.getByText('Agendado',{exact:false}).count());
 assert.ok(await page.evaluate(()=>window.__atlasFixture.calls.some(c=>c.name==='atlas_team_context'&&c.p_thread==='cccccccc-cccc-4ccc-8ccc-cccccccccccc')));
 checks.push('keyboard opens exact scheduled robot consultation');
 await page.screenshot({path:new URL('desktop.png',output).pathname,fullPage:true});
 await page.keyboard.press('Escape');
 await page.evaluate(()=>window.__atlasFixture.complete());
 await page.getByText(/Conta Exemplo informou em 19\/10 09:00: ainda está em edição/).waitFor({timeout:7000});
 assert.equal(await page.getByText('Pergunta agendada para Conta Exemplo em 19/10 08:00.',{exact:true}).count(),0);
 checks.push('team answer replaces pending result in original conversation');
 await page.getByRole('button',{name:'Memória',exact:true}).click();
 const sharing=page.getByRole('checkbox',{name:'Autorizar esta informação nas conversas com a equipe deste cliente'});
 await sharing.check();assert.equal(await sharing.isChecked(),true);
 await page.getByText('Informação autorizada para as conversas com a equipe deste cliente.',{exact:true}).waitFor();
 await page.evaluate(()=>window.__atlasFixture.failShare=true);await sharing.click();
 await page.getByRole('alert').filter({hasText:'Falha de rede fictícia.'}).waitFor();assert.equal(await sharing.isChecked(),true);
 await page.evaluate(()=>window.__atlasFixture.failShare=false);await sharing.uncheck();assert.equal(await sharing.isChecked(),false);
 checks.push('sharing opt-in works; failed update preserves previous permission');
 await page.getByLabel('Contexto',{exact:true}).selectOption('');
 const general=page.locator('.atlas-memory-item').filter({hasText:'Memória privada geral.'});await general.waitFor();assert.equal(await general.getByRole('checkbox').count(),0);
 checks.push('global memory has no team-sharing action');
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Conversa',exact:true}).click();
 await page.screenshot({path:new URL('mobile.png',output).pathname,fullPage:true});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'mobile page overflow');
 checks.push('mobile layout fits viewport');
 assert.deepEqual(errors,[]);assert.deepEqual(external,[]);
 checks.push('no browser exceptions or external network requests');
 writeFileSync(new URL('results.json',output),JSON.stringify({checks,errors,external},null,2));
 console.log(JSON.stringify({checks:checks.length,passed:checks,external_requests:external.length}));
}finally{await browser.close();}
