const { chromium } = require(process.env.ATLAS_PLAYWRIGHT_MODULE || 'playwright');
const fs = require('fs');
const path = require('path');
const outputDirectory = path.resolve(__dirname, '../../.local/atlas-preview');
fs.mkdirSync(outputDirectory, { recursive: true });
const assert = (condition, message) => { if (!condition) throw new Error(message); };
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.ATLAS_CHROME_PATH || undefined });
  const page = await browser.newPage({ viewport: { width: 1280, height: 1100 } });
  const errors = [];
  const blocked = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.route('**/*', route => {
    const url = new URL(route.request().url());
    if (url.hostname === '127.0.0.1') return route.continue();
    blocked.push(url.origin); return route.abort();
  });
  const start = async (suffix = '') => { await page.goto('http://127.0.0.1:4317/' + suffix); };
  const ready = async () => page.getByRole('heading', { name: 'O que vamos resolver hoje?' }).waitFor();
  const waitDone = async () => page.waitForFunction(() => !document.querySelector('#atlas-message').disabled && document.querySelector('#atlas-message').value === '');
  await start(); await ready();
  await page.getByRole('button', { name: /^Estratégia e criação Sem missão/ }).click();
  assert((await page.locator('#atlas-agent-detail').innerText()).includes('Conduzir brainstorm'), 'Server skills missing');
  await page.getByRole('button', { name: 'Clareza para o dia' }).click();
  assert((await page.locator('#atlas-message').inputValue()).includes('decisão'), 'Prompt not filled');
  await page.getByRole('button', { name: 'Enviar', exact: true }).click(); await waitDone();
  assert(await page.locator('.atlas-message').count() === 2, 'Chat messages not rendered');
  await page.getByRole('button', { name: 'Missões', exact: true }).click();
  assert(await page.locator('.atlas-mission').count() === 1, 'Mission not loaded');
  assert((await page.locator('.atlas-steps').innerText()).includes('Operação'), 'Agent step not present');
  await page.getByRole('button', { name: 'Conversa', exact: true }).click();
  await page.getByLabel('Contexto', { exact: true }).selectOption('11111111-1111-4111-8111-111111111111');
  assert(await page.locator('.atlas-message').count() === 0, 'Scope did not start a new conversation');
  await page.locator('#atlas-message').fill('Pedido que precisa recuperar uma resposta.');
  await page.evaluate(() => window.__atlasTest.queue.push('network'));
  await page.getByRole('button', { name: 'Enviar', exact: true }).click();
  await page.getByRole('button', { name: 'Reenviar', exact: true }).waitFor();
  assert((await page.locator('#atlas-message').inputValue()).includes('recuperar'), 'Composer lost on network error');
  await page.getByRole('button', { name: 'Reenviar', exact: true }).click(); await waitDone();
  const retryCalls = await page.evaluate(() => window.__atlasTest.calls.filter(x => x.action === 'chat'));
  assert(retryCalls[1].payload.request_id === retryCalls[2].payload.request_id, 'Unknown outcome did not preserve request id');
  await page.locator('#atlas-message').fill('Pedido com falha terminal.');
  await page.evaluate(() => window.__atlasTest.queue.push('failed'));
  await page.getByRole('button', { name: 'Enviar', exact: true }).click();
  await page.getByRole('button', { name: 'Nova tentativa', exact: true }).waitFor();
  assert((await page.locator('#atlas-message').inputValue()).includes('terminal'), 'Composer lost on terminal failure');
  assert((await page.locator('.atlas-agent-operacao').innerText()).includes('Interrompido'), 'Failed run treated completed read as completed specialist');
  await page.getByRole('button', { name: 'Nova tentativa', exact: true }).click(); await waitDone();
  const terminalCalls = await page.evaluate(() => window.__atlasTest.calls.filter(x => x.action === 'chat').slice(-2));
  assert(terminalCalls[0].payload.request_id !== terminalCalls[1].payload.request_id, 'Terminal retry reused failed request id');
  assert(terminalCalls[0].payload.conversation_id === terminalCalls[1].payload.conversation_id, 'Terminal retry lost conversation');
  await page.locator('#atlas-message').fill('Missão com acompanhamento real.');
  await page.evaluate(() => window.__atlasTest.queue.push('processing'));
  await page.getByRole('button', { name: 'Enviar', exact: true }).click();
  await page.getByText('Missão em andamento. Consultando o resultado…', { exact: true }).waitFor();
  assert(await page.locator('#atlas-message').isDisabled(), 'Composer not blocked for actual processing run');
  assert((await page.locator('.atlas-agent-operacao').innerText()).includes('Em andamento'), 'Completed read marked a running specialist complete');
  await page.evaluate(() => { window.__atlasTest.releaseProcessing = true; });
  await waitDone();
  await page.getByRole('button', { name: 'Memória', exact: true }).click();
  await page.getByLabel('Nova memória', { exact: true }).fill('Sempre apresentar três caminhos criativos.');
  assert(await page.getByRole('button', { name: 'Confirmar e salvar' }).isDisabled(), 'Memory saved without confirmation');
  await page.getByRole('checkbox').check();
  await page.getByLabel('Onde usar', { exact: true }).selectOption('');
  assert(!(await page.getByRole('checkbox').isChecked()), 'Scope change retained stale confirmation');
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Confirmar e salvar' }).click();
  await page.getByText('Memória confirmada e salva.', { exact: true }).waitFor();
  assert(await page.locator('.atlas-memory-item').count() === 1, 'Saved memory not shown');
  await page.getByRole('button', { name: 'Corrigir', exact: true }).click();
  assert(!(await page.getByRole('checkbox').isChecked()), 'Correction retained confirmation');
  assert(await page.getByLabel('Onde usar', { exact: true }).isDisabled(), 'Correction allowed changing memory scope');
  await page.getByLabel('Corrigir memória', { exact: true }).fill('Apresentar dois caminhos criativos e recomendar um.');
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Confirmar correção', exact: true }).click();
  await page.getByText('Correção confirmada. A nova versão substitui a anterior.', { exact: true }).waitFor();
  assert(await page.locator('.atlas-memory-item').count() === 1, 'Correction left old memory active');
  assert((await page.locator('.atlas-memory-item').innerText()).includes('versão 2'), 'Memory version missing');
  const memoryCalls = await page.evaluate(() => window.__atlasTest.calls.filter(item => item.action === 'save_memory'));
  assert(Boolean(memoryCalls[1].payload.replaces_id), 'Correction did not send replaces id');
  await page.getByRole('button', { name: 'Revogar', exact: true }).click();
  await page.getByRole('button', { name: 'Revogar memória', exact: true }).click();
  await page.getByText('Memória revogada. Ela não será usada em novas consultas.', { exact: true }).waitFor();
  assert(await page.locator('.atlas-memory-item').count() === 0, 'Revoked memory still shown');
  await page.locator('.atlas-history summary').click();
  await page.getByRole('button', { name: /^Organizar as prioridades da semana/ }).click();
  await page.getByText('Como podemos organizar as prioridades?', { exact: true }).waitFor();
  assert(await page.getByLabel('Contexto', { exact: true }).inputValue() === '', 'History loaded wrong scope');
  const layouts = [];
  for (const width of [1280, 736, 320]) {
    await start(); await ready(); await page.setViewportSize({ width, height: 1100 }); await page.waitForTimeout(100);
    const layout = await page.evaluate(() => ({ width: window.innerWidth, scroll: document.documentElement.scrollWidth }));
    assert(layout.scroll <= layout.width, 'Horizontal overflow at ' + width);
    await page.getByRole('button', { name: 'Ocultar conversa', exact: true }).click();
    assert(!(await page.locator('#atlas-workspace').isVisible()), 'Chat did not collapse');
    await page.screenshot({ path: path.join(outputDirectory, `atlas-map-${width}.png`), fullPage: true });
    await page.getByRole('button', { name: 'Abrir conversa', exact: true }).click();
    assert(await page.locator('#atlas-workspace').isVisible(), 'Chat did not reopen');
    layouts.push(layout); await page.screenshot({ path: path.join(outputDirectory, `atlas-${width}.png`), fullPage: true });
  }
  for (const [mode, title] of [['forbidden','Este espaço é pessoal'],['disabled','Atlas ainda não habilitado'],['unconfigured','O Atlas está sendo preparado'],['error','Não foi possível abrir o Atlas'],['unauthenticated','Entre para abrir o Atlas']]) {
    await start('?case=' + mode); await page.getByRole('heading', { name: title, exact: true }).waitFor();
    assert(await page.locator('#atlas-message').count() === 0, 'Gate rendered composer for ' + mode);
  }
  assert(errors.length === 0, 'Runtime errors: ' + errors.join('; '));
  assert(blocked.length === 0, 'Unexpected external requests: ' + blocked.join('; '));
  const result = { passed: ['chat', 'history', 'client context', 'server skill catalog', 'network retry idempotency', 'terminal retry new id', 'processing history polling', 'completed read does not complete specialist', 'failed run interrupts unfinished specialist', 'memory explicit confirmation', 'memory confirmation reset on scope change', 'memory correction replaces version with new confirmation', 'memory revoke', 'forbidden gate', 'disabled gate', 'unconfigured gate', 'error gate', 'session expired gate', 'responsive layouts', 'collapsible conversation preserves workspace'], layouts, runtimeErrors: errors, externalRequests: blocked };
  fs.writeFileSync(path.join(outputDirectory, 'verification.json'), JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result, null, 2)); await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
