/* Service Worker desativado — limpa caches antigos e não intercepta requisições. */
self.addEventListener('install', () => {
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.map((key) => caches.delete(key))))
      .then(() => self.registration.unregister())
      .then(() => self.clients.claim())
  );
});

// Sem listener "fetch": nenhuma requisição (Supabase, APIs) é interceptada.
